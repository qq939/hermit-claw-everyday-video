// studio/providers/local-longform.js
// Offline longform Markdown writer. Pure Node, zero network.
// Produces a .md file in studio-assets/. The agent then composes
// its own copy (this is just a structural scaffold).

const fs = require('fs');
const path = require('path');

const PROJECT_DIR = path.resolve(__dirname, '..', '..', '..');
const ASSETS_DIR = path.join(PROJECT_DIR, 'studio-assets');

function _ts() { return new Date().toISOString().replace(/[:.]/g, '-'); }
function _rnd() { return Math.random().toString(36).slice(2, 8); }

async function probe() { return { enabled: true, mode: 'markdown' }; }

async function run(request) {
    const { title = 'untitled', subtitle = '', body = '', palette } = request || {};
    const lines = [
        `# ${title}`,
        '',
        subtitle ? `> ${subtitle}` : '',
        '',
        `*generated by Hermit-Claw · studio · ${new Date().toISOString()}*`,
        '',
        '---',
        '',
        body || '_（等待 Agent 补全正文）_',
        '',
        '---',
        '',
        '## 备注',
        '',
        `- palette: ${(palette || []).join(' / ') || 'default'}`,
        `- 本文档由本地 longform provider 生成，未走网络。`,
        '',
    ].filter((l) => l !== null);
    const out = lines.join('\n');
    fs.mkdirSync(ASSETS_DIR, { recursive: true });
    const dest = path.join(ASSETS_DIR, `longform-${_ts()}-${_rnd()}.md`);
    fs.writeFileSync(dest, out, 'utf8');
    return {
        ok: true,
        kind: 'longform',
        path: dest,
        bytes: Buffer.byteLength(out, 'utf8'),
        assetUrl: `/api/studio/asset/${path.basename(dest)}`,
        mime: 'text/markdown',
    };
}

module.exports = {
    id: 'local-longform',
    kind: 'longform',
    label: '本地 Markdown 长文（零依赖）',
    probe,
    isEnabled: () => true,
    run,
};